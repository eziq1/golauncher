// cities.json is the curated overlay: major cities with Chinese names,
// aliases and the default list (docs/world-clock.md §9.3).
//
//go:embed cities.json
var citiesJSON []byte

// geonames.tsv.gz holds the GeoNames cities with a population of 15,000 or
// more (CC BY 4.0), generated by scripts/gencities (docs/world-clock.md §9.2).
//
//go:embed geonames.tsv.gz
var geonamesData []byte

// city is a place with a clock.
type city struct {
	ID        string   `json:"id"`
	GeonameID int      `json:"geonameid"`
	Name      string   `json:"name"`
	Zh        string   `json:"zh"`
	Country   string   `json:"country"`
	CountryZh string   `json:"countryZh"`
	TZ        string   `json:"tz"`
	Aliases   []string `json:"aliases"`

	ascii     string // ASCII name, when it differs from Name
	cc        string // ISO country code ("" for UTC)
	region    string // first-level division (state, province)
	regionZh  string
	curated   bool // from cities.json
	ambiguous bool // another city has the same name

	loc  *time.Location
	keys []matchKey // names, pinyin and aliases (and countries of curated cities)
	ord  int        // position in index.cities: curated first, then by population
}

// matchKey is a normalized string a query is matched against, with the
// forms scoreKey compares precomputed.
type matchKey struct {
	s        string
	w        float64 // weight of a match on this key
	exact    bool    // only an exact match counts (pinyin initials)
	compact  string  // s without spaces
	initials string  // first letters of the words when there are several
}

func newMatchKey(s string, w float64) matchKey {
	k := matchKey{s: s, w: w, compact: strings.ReplaceAll(s, " ", "")}
	if words := strings.FieldsFunc(s, isWordSep); len(words) > 1 {
		var ini strings.Builder
		for _, w := range words {
			r, _ := utf8.DecodeRuneInString(w)
			ini.WriteRune(r)
		}
		k.initials = ini.String()
	}
	return k
}

// isWordSep separates the words of a key: spaces and the slashes of zone
// IDs.
func isWordSep(r rune) bool { return r == ' ' || r == '/' }

// laterWords calls fn with each word of s after the first, as a suffix of s
// starting at the word ("asia/ho chi minh" -> "ho chi minh", "chi minh",
// "minh"). Words are not stored, which saves memory with 30,000 cities.
func laterWords(s string, fn func(rest string) bool) {
	sep := func(b byte) bool { return b == ' ' || b == '/' }
	i := 0
	for i < len(s) && sep(s[i]) { // separators before the first word
		i++
	}
	for i < len(s) && !sep(s[i]) { // the first word
		i++
	}
	for ; i < len(s)-1; i++ {
		if sep(s[i]) && !sep(s[i+1]) && fn(s[i+1:]) {
			return
		}
	}
}

// Weights of the kinds of keys.
const (
	weightName    = 1.0
	weightCountry = 0.8
	weightZone    = 0.85
	// scoreOffset and scoreAbbr are the scores of cities found by UTC offset
	// ("utc+8") or time zone abbreviation ("pst").
	scoreOffset = 0.9
	scoreAbbr   = 0.9
)

// country is a country of the GeoNames data with its cities.
type country struct {
	code, name, zh string
	keys           []matchKey
	cities         []int32 // ords, ascending
}

// zone is an IANA time zone with its cities.
type zone struct {
	id     string
	loc    *time.Location
	keys   []matchKey
	cities []int32 // ords, ascending
}

// index holds the cities with their match keys and locations, the
// countries and zones, and the lookup tables (docs/world-clock.md §9.5).
type index struct {
	cities    []*city
	countries []*country
	zones     []*zone
	zoneByID  map[string]*zone
	names     nameIndex

	byID        map[string]*city // curated cities
	byGeonameID []int32          // ords of the GeoNames cities by GeoNames ID
	zoneByLower map[string]*zone // lowercase zone IDs
}

// sharedIndex is the index of the embedded cities, built once per process:
// it is read-only after it is built, so every plugin instance (tests and
// glctl create many) shares it.
var sharedIndex = sync.OnceValues(loadIndex)

// loadIndex loads the embedded cities.
func loadIndex() (*index, error) {
	return buildIndex(citiesJSON, bytes.NewReader(geonamesData))
}

// buildIndex reads the curated cities (JSON) and the gzip'd GeoNames data,
// merges them, loads the time zones and builds the match keys and lookup
// tables.
func buildIndex(curatedJSON []byte, geonames io.Reader) (*index, error) {
	var curated []*city
	if err := json.Unmarshal(curatedJSON, &curated); err != nil {
		return nil, fmt.Errorf("clock: cities.json: %w", err)
	}
	g, err := parseGeonames(geonames)
	if err != nil {
		return nil, err
	}
	idx := &index{zoneByID: map[string]*zone{}, byID: map[string]*city{}}
	byGeoname := map[int]*city{}
	for _, c := range curated {
		if _, dup := idx.byID[c.ID]; dup {
			return nil, fmt.Errorf("clock: duplicate city id %q", c.ID)
		}
		if _, err := idx.zone(c.TZ); err != nil {
			return nil, fmt.Errorf("clock: city %s: %w", c.ID, err)
		}
		c.curated = true
		idx.add(c)
		if c.GeonameID != 0 {
			byGeoname[c.GeonameID] = c
		}
	}
	countries := map[string]*country{}
	for _, c := range g.countries {
		countries[c.code] = c
		idx.countries = append(idx.countries, c)
	}
	for _, row := range g.cities {
		r := g.regions[row.cc+"."+row.admin1]
		if c, ok := byGeoname[row.id]; ok {
			// The overlay wins; GeoNames adds the region and country code.
			c.cc, c.region, c.regionZh = row.cc, r.name, r.zh
			continue
		}
		if _, err := idx.zone(row.tz); err != nil {
			continue // a zone this Go does not know; the generator checks them
		}
		c := &city{ID: strconv.Itoa(row.id), GeonameID: row.id, Name: row.name, ascii: row.ascii, Zh: row.zh,
			TZ: row.tz, cc: row.cc, region: r.name, regionZh: r.zh}
		if co := countries[row.cc]; co != nil {
			c.Country, c.CountryZh = co.name, co.zh
		}
		idx.add(c)
	}
	idx.finish(countries)
	return idx, nil
}

// add appends c to the cities.
func (idx *index) add(c *city) {
	c.ord = len(idx.cities)
	idx.cities = append(idx.cities, c)
	if c.curated {
		idx.byID[c.ID] = c
	}
}

// zone returns the zone with IANA ID id, loading it the first time.
func (idx *index) zone(id string) (*zone, error) {
	if z, ok := idx.zoneByID[id]; ok {
		return z, nil
	}
	loc, err := time.LoadLocation(id)
	if err != nil {
		return nil, err
	}
	z := &zone{id: id, loc: loc}
	z.keys = append(z.keys, newMatchKey(normalize(id), weightZone))
	if _, last, ok := strings.Cut(id, "/"); ok {
		if i := strings.LastIndex(last, "/"); i >= 0 {
			last = last[i+1:]
		}
		z.keys = append(z.keys, newMatchKey(normalize(strings.ReplaceAll(last, "_", " ")), weightZone))
	}
	idx.zoneByID[id] = z
	idx.zones = append(idx.zones, z)
	return z, nil
}

// finish computes what needs all cities: locations, match keys, the city
// lists of countries and zones, ambiguous names, the lookup tables and the
// name index.
func (idx *index) finish(countries map[string]*country) {
	names := map[string]int{}
	nNames := make([]string, len(idx.cities))
	for _, c := range idx.cities {
		z := idx.zoneByID[c.TZ]
		c.loc = z.loc
		z.cities = append(z.cities, int32(c.ord))
		if co := countries[c.cc]; co != nil {
			co.cities = append(co.cities, int32(c.ord))
		}
		c.keys = cityKeys(c)
		n := normalize(c.Name)
		names[n]++
		nNames[c.ord] = n
		if !c.curated {
			idx.byGeonameID = append(idx.byGeonameID, int32(c.ord))
		}
	}
	for _, c := range idx.cities {
		c.ambiguous = names[nNames[c.ord]] > 1
	}
	slices.SortFunc(idx.byGeonameID, func(a, b int32) int {
		return cmp.Compare(idx.cities[a].GeonameID, idx.cities[b].GeonameID)
	})
	idx.zoneByLower = make(map[string]*zone, len(idx.zones))
	for _, z := range idx.zones {
		idx.zoneByLower[strings.ToLower(z.id)] = z
	}
	for _, co := range idx.countries {
		co.keys = nil
		add := func(s string) {
			if s = normalize(s); s != "" {
				co.keys = append(co.keys, newMatchKey(s, weightCountry))
			}
		}
		add(co.name)
		add(co.zh)
		if full, initials := pinyinOf(co.zh); full != "" {
			add(full)
			co.keys = append(co.keys, matchKey{s: initials, w: weightCountry, exact: true})
		}
	}
	idx.names = newNameIndex(idx.cities)
}

// chinaCodes are the countries whose cities' pinyin initials are matched
// ("sz" for 深圳); initials of transliterated foreign names mean nothing.
var chinaCodes = map[string]bool{"CN": true, "TW": true, "HK": true, "MO": true}

// cityKeys returns the match keys of c: names, Chinese name and its pinyin,
// aliases, and for curated cities also their country. Countries and zones of
// all cities are matched through index.countries and index.zones.
func cityKeys(c *city) []matchKey {
	var keys []matchKey
	add := func(s string, w float64) {
		if s = normalize(s); s != "" && !slices.ContainsFunc(keys, func(k matchKey) bool { return k.s == s && k.w == w }) {
			keys = append(keys, newMatchKey(s, w))
		}
	}
	addHan := func(s string, w float64, initials bool) {
		add(s, w)
		if full, ini := pinyinOf(s); full != "" {
			add(full, w)
			// Initials only count as exact matches: as prefixes or
			// substrings they would match almost anything.
			if initials {
				keys = append(keys, matchKey{s: ini, w: w, exact: true})
			}
		}
	}
	add(c.Name, weightName)
	add(c.ascii, weightName)
	addHan(c.Zh, weightName, c.curated || chinaCodes[c.cc])
	for _, a := range c.Aliases {
		addHan(a, weightName, true)
	}
	if c.curated {
		add(c.Country, weightCountry)
		addHan(c.CountryZh, weightCountry, true)
	}
	return keys
}

// geonames is the parsed GeoNames data file.
type geonames struct {
	countries []*country
	regions   map[string]regionName // "US.IL"
	cities    []geonameRow          // by population, largest first
}

type regionName struct{ name, zh string }

type geonameRow struct {
	id                              int
	name, ascii, zh, cc, admin1, tz string
}

// parseGeonames parses the gzip'd TSV written by scripts/gencities:
// sections "#countries" (code, name, Chinese name), "#admin1" ("US.IL",
// name, Chinese name) and "#cities" (GeoNames ID, name, ASCII name, Chinese
// name, country code, admin1 code, time zone). Other lines starting with
// "#" are comments.
func parseGeonames(r io.Reader) (*geonames, error) {
	zr, err := gzip.NewReader(r)
	if err != nil {
		return nil, fmt.Errorf("clock: city data: %w", err)
	}
	g := &geonames{regions: map[string]regionName{}}
	sc := bufio.NewScanner(zr)
	section := ""
	line := 0
	for sc.Scan() {
		line++
		s := sc.Text()
		if s == "" {
			continue
		}
		if s[0] == '#' {
			switch s {
			case "#countries", "#admin1", "#cities":
				section = s
			}
			continue
		}
		f := strings.Split(s, "\t")
		bad := func() error { return fmt.Errorf("clock: city data line %d: %d fields in %s", line, len(f), section) }
		switch section {
		case "#countries":
			if len(f) != 3 {
				return nil, bad()
			}
			g.countries = append(g.countries, &country{code: f[0], name: f[1], zh: f[2]})
		case "#admin1":
			if len(f) != 3 {
				return nil, bad()
			}
			g.regions[f[0]] = regionName{f[1], f[2]}
		case "#cities":
			if len(f) != 7 {
				return nil, bad()
			}
			id, err := strconv.Atoi(f[0])
			if err != nil {
				return nil, fmt.Errorf("clock: city data line %d: %w", line, err)
			}
			g.cities = append(g.cities, geonameRow{id: id, name: f[1], ascii: f[2], zh: f[3], cc: f[4], admin1: f[5], tz: f[6]})
		default:
			return nil, fmt.Errorf("clock: city data line %d: outside a section", line)
		}
	}
	if err := sc.Err(); err != nil {
		return nil, fmt.Errorf("clock: city data: %w", err)
	}
	return g, nil
}

var pinyinArgs = pinyin.NewArgs()

// pinyinOf returns the pinyin of the Han characters in s ("北京" ->
// "beijing", "bj"), or "" when s has none.
func pinyinOf(s string) (full, initials string) {
	if s == "" {
		return "", ""
	}
	syl := pinyin.LazyPinyin(s, pinyinArgs)
	if len(syl) == 0 {
		return "", ""
	}
	var ini strings.Builder
	for _, p := range syl {
		ini.WriteByte(p[0])
	}
	return strings.Join(syl, ""), ini.String()
}

// stripMarks removes diacritics: "São Paulo" -> "Sao Paulo".
var stripMarks = transform.Chain(norm.NFD, runes.Remove(runes.In(unicode.Mn)), norm.NFC)

// normalize lowercases s, removes diacritics and punctuation that is often
// left out ("Xi'an", "Washington, D.C.") and collapses spaces. Slashes of
// time zone IDs are kept.
func normalize(s string) string {
	ascii := true
	for i := 0; i < len(s); i++ {
		if s[i] >= utf8.RuneSelf {
			ascii = false
			break
		}
	}
	if !ascii {
		if t, _, err := transform.String(stripMarks, s); err == nil {
			s = t
		}
	}
	s = strings.Map(func(r rune) rune {
		switch r {
		case '\'', '’', '.', ',':
			return -1
		case '-', '_':
			return ' '
		}
		return unicode.ToLower(r)
	}, s)
	return strings.Join(strings.Fields(s), " ")
}

// scoreKey scores query q (normalized; qc is q without spaces) against
// key k: 1 for an exact match, less for prefixes, word prefixes, initials,
// substrings and subsequences, 0 for no match. Scores of at least
// strongScore come from the name index; weaker ones (substrings and
// subsequences) only from a full scan.
func scoreKey(q, qc string, k *matchKey) float64 {
	if k.exact {
		if q == k.s {
			return 1
		}
		return 0
	}
	kc := k.compact
	switch {
	case q == k.s, qc == kc: // "newyork"
		return 1
	case strings.HasPrefix(kc, qc):
		return 0.9
	}
	// A query without separators is a prefix of a word exactly when it is a
	// prefix of the rest of the key starting at that word.
	if !strings.ContainsAny(q, " /") {
		word := false
		laterWords(k.s, func(rest string) bool {
			word = strings.HasPrefix(rest, q)
			return word
		})
		if word {
			return 0.8 // "york", "shanghai" in "asia/shanghai"
		}
	}
	if k.initials != "" && len(qc) >= 2 {
		switch {
		case k.initials == qc:
			return 0.9 // "hcmc"
		case strings.HasPrefix(k.initials, qc):
			return 0.75
		}
	}
	if utf8.RuneCountInString(qc) >= 2 && strings.Contains(kc, qc) {
		return 0.6
	}
	if len(qc) >= 4 && qc[0] == kc[0] && subsequence(qc, kc) {
		return 0.3 + 0.2*float64(len(qc))/float64(len(kc))
	}
	return 0
}

// strongScore is the least score scoreKey gives for an exact match, a
// prefix, a word prefix or initials; substrings and subsequences score less.
const strongScore = 0.75

// subsequence reports whether the runes of q appear in k in order.
func subsequence(q, k string) bool {
	qr := []rune(q)
	i := 0
	for _, r := range k {
		if i < len(qr) && r == qr[i] {
			i++
		}
	}
	return i == len(qr)
}

// bestKey is the best weighted score of q against keys.
func bestKey(q, qc string, keys []matchKey) float64 {
	best := 0.0
	for i := range keys {
		k := &keys[i]
		best = max(best, k.w*scoreKey(q, qc, k))
	}
	return best
}

// offsetQuery is a query for a UTC offset.
type offsetQuery struct {
	seconds int
	ok      bool
}

// parseOffset parses "utc+8", "gmt-5:30", "UTC+0545", "+8" and "utc" (a
// normalized query) as a UTC offset.
func parseOffset(q string) offsetQuery {
	q = strings.ReplaceAll(q, " ", "")
	q = strings.ReplaceAll(q, "−", "-") // minus sign
	rest, named := strings.CutPrefix(q, "utc")
	if !named {
		rest, named = strings.CutPrefix(q, "gmt")
	}
	if rest == "" {
		return offsetQuery{0, named}
	}
	sign := 1
	switch rest[0] {
	case '+':
	case '-':
		sign = -1
	default:
		return offsetQuery{}
	}
	rest = rest[1:]
	h, m, colon := strings.Cut(rest, ":")
	if !colon && len(rest) > 2 {
		h, m = rest[:len(rest)-2], rest[len(rest)-2:] // "0530"
	}
	hours, ok := digits(h, 1, 2)
	if !ok || hours > 14 {
		return offsetQuery{}
	}
	minutes := 0
	if colon || m != "" {
		if minutes, ok = digits(m, 2, 2); !ok || minutes >= 60 {
			return offsetQuery{}
		}
	}
	return offsetQuery{sign * (hours*3600 + minutes*60), true}
}

// digits parses a decimal number of minLen to maxLen ASCII digits.
func digits(s string, minLen, maxLen int) (int, bool) {
	if len(s) < minLen || len(s) > maxLen {
		return 0, false
	}
	n := 0
	for _, r := range s {
		if r < '0' || r > '9' {
			return 0, false
		}
		n = n*10 + int(r-'0')
	}
	return n, true
}

