// trad maps traditional characters to simplified ones.
var trad = func() map[rune]rune {
	m := map[rune]rune{}
	rs := []rune(strings.Join(strings.Fields(tradPairs), ""))
	if len(rs)%2 != 0 {
		panic("gencities: tradPairs has an odd number of characters")
	}
	for i := 0; i < len(rs); i += 2 {
		m[rs[i]] = rs[i+1]
	}
	return m
}()
