// Command geniconsgen draws the golauncher icon and writes it to the assets
// directory as icon.svg, one PNG per size (icon-16.png … icon-256.png) and a
// multi-size icon.ico. The SVG and the bitmaps come from the same geometry
// below, so they always match:
//
//	go run ./scripts/geniconsgen            # writes ./assets
//	go run ./scripts/geniconsgen -out DIR
//
// The icon is a rounded square with a vertical accent-blue gradient and a
// white magnifying glass. Bitmaps are rendered from signed distances with
// 8×8 supersampling, so only the standard library is needed.
package main

import (
	"bytes"
	"encoding/binary"
	"flag"
	"fmt"
	"image"
	"image/color"
	"image/png"
	"log"
	"math"
	"os"
	"path/filepath"
)

// The geometry, in a 256×256 view box.
const (
	view = 256.0

	tileMin    = 8.0   // the tile spans [tileMin, view-tileMin] on both axes
	tileRadius = 56.0  // corner radius of the tile
	ringX      = 112.0 // centre of the lens
	ringY      = 112.0
	ringR      = 50.0 // radius of the lens, to the middle of its stroke
	ringW      = 22.0 // stroke width of the lens
	handleW    = 28.0 // stroke width of the handle (round caps)
	handleEndX = 186.0
	handleEndY = 186.0
)

// The handle starts on the outer edge of the ring, along the diagonal.
var (
	handleStartX = ringX + (ringR+ringW/2-4)*math.Sqrt2/2
	handleStartY = ringY + (ringR+ringW/2-4)*math.Sqrt2/2
)

// Colors: the gradient from top to bottom, and the glyph.
var (
	topColor    = color.NRGBA{R: 0x4C, G: 0x8D, B: 0xF8, A: 0xFF}
	bottomColor = color.NRGBA{R: 0x25, G: 0x63, B: 0xEB, A: 0xFF}
	glyphColor  = color.NRGBA{R: 0xFF, G: 0xFF, B: 0xFF, A: 0xFF}
)

var sizes = []int{16, 24, 32, 48, 64, 128, 256}

func main() {
	out := flag.String("out", "assets", "output directory")
	flag.Parse()
	if err := run(*out); err != nil {
		log.Fatal(err)
	}
}

func run(out string) error {
	if err := os.MkdirAll(out, 0o755); err != nil {
		return err
	}
	if err := os.WriteFile(filepath.Join(out, "icon.svg"), []byte(svg()), 0o644); err != nil {
		return err
	}
	var pngs [][]byte
	for _, n := range sizes {
		var b bytes.Buffer
		if err := png.Encode(&b, render(n)); err != nil {
			return err
		}
		pngs = append(pngs, b.Bytes())
		if err := os.WriteFile(filepath.Join(out, fmt.Sprintf("icon-%d.png", n)), b.Bytes(), 0o644); err != nil {
			return err
		}
	}
	return os.WriteFile(filepath.Join(out, "icon.ico"), ico(sizes, pngs), 0o644)
}

// svg renders the icon as SVG.
func svg() string {
	side := view - 2*tileMin
	return fmt.Sprintf(`<svg xmlns="http://www.w3.org/2000/svg" width="256" height="256" viewBox="0 0 256 256">
  <!-- Generated by scripts/geniconsgen; edit the geometry there. -->
  <defs>
    <linearGradient id="bg" x1="0" y1="0" x2="0" y2="1">
      <stop offset="0" stop-color="%s"/>
      <stop offset="1" stop-color="%s"/>
    </linearGradient>
  </defs>
  <rect x="%g" y="%g" width="%g" height="%g" rx="%g" fill="url(#bg)"/>
  <g fill="none" stroke="%s" stroke-linecap="round">
    <circle cx="%g" cy="%g" r="%g" stroke-width="%g"/>
    <line x1="%.2f" y1="%.2f" x2="%g" y2="%g" stroke-width="%g"/>
  </g>
</svg>
`, hex(topColor), hex(bottomColor),
		tileMin, tileMin, side, side, tileRadius,
		hex(glyphColor),
		ringX, ringY, ringR, ringW,
		handleStartX, handleStartY, handleEndX, handleEndY, handleW)
}

func hex(c color.NRGBA) string { return fmt.Sprintf("#%02X%02X%02X", c.R, c.G, c.B) }

// render draws the icon at n×n pixels.
func render(n int) *image.NRGBA {
	const ss = 8 // samples per axis
	img := image.NewNRGBA(image.Rect(0, 0, n, n))
	scale := view / float64(n)
	for py := range n {
		for px := range n {
			// Accumulate premultiplied color over the samples.
			var r, g, b, a float64
			for sy := range ss {
				for sx := range ss {
					x := (float64(px) + (float64(sx)+0.5)/ss) * scale
					y := (float64(py) + (float64(sy)+0.5)/ss) * scale
					if !inTile(x, y) {
						continue
					}
					c := gradient(y)
					if inGlyph(x, y) {
						c = glyphColor
					}
					r += float64(c.R)
					g += float64(c.G)
					b += float64(c.B)
					a++
				}
			}
			if a == 0 {
				continue
			}
			img.SetNRGBA(px, py, color.NRGBA{
				R: uint8(math.Round(r / a)),
				G: uint8(math.Round(g / a)),
				B: uint8(math.Round(b / a)),
				A: uint8(math.Round(255 * a / ss / ss)),
			})
		}
	}
	return img
}

func inTile(x, y float64) bool {
	lo, hi := tileMin+tileRadius, view-tileMin-tileRadius
	cx := min(max(x, lo), hi)
	cy := min(max(y, lo), hi)
	if x < tileMin || x > view-tileMin || y < tileMin || y > view-tileMin {
		return false
	}
	return math.Hypot(x-cx, y-cy) <= tileRadius
}

func inGlyph(x, y float64) bool {
	if math.Abs(math.Hypot(x-ringX, y-ringY)-ringR) <= ringW/2 {
		return true
	}
	return segmentDistance(x, y, handleStartX, handleStartY, handleEndX, handleEndY) <= handleW/2
}

// segmentDistance is the distance from (x, y) to the segment (ax, ay)–(bx, by).
func segmentDistance(x, y, ax, ay, bx, by float64) float64 {
	dx, dy := bx-ax, by-ay
	t := ((x-ax)*dx + (y-ay)*dy) / (dx*dx + dy*dy)
	t = min(max(t, 0), 1)
	return math.Hypot(x-(ax+t*dx), y-(ay+t*dy))
}

func gradient(y float64) color.NRGBA {
	t := min(max((y-tileMin)/(view-2*tileMin), 0), 1)
	mix := func(a, b uint8) uint8 { return uint8(math.Round(float64(a) + t*(float64(b)-float64(a)))) }
	return color.NRGBA{
		R: mix(topColor.R, bottomColor.R),
		G: mix(topColor.G, bottomColor.G),
		B: mix(topColor.B, bottomColor.B),
		A: 0xFF,
	}
}

// ico packs PNG images into an ICO file (PNG entries, Windows Vista and
// later).
func ico(sizes []int, pngs [][]byte) []byte {
	var b bytes.Buffer
	le := binary.LittleEndian
	_ = binary.Write(&b, le, [3]uint16{0, 1, uint16(len(pngs))})
	offset := 6 + 16*len(pngs)
	for i, data := range pngs {
		dim := byte(sizes[i])
		if sizes[i] >= 256 {
			dim = 0
		}
		b.Write([]byte{dim, dim, 0, 0})
		_ = binary.Write(&b, le, [2]uint16{1, 32}) // planes, bits per pixel
		_ = binary.Write(&b, le, [2]uint32{uint32(len(data)), uint32(offset)})
		offset += len(data)
	}
	for _, data := range pngs {
		b.Write(data)
	}
	return b.Bytes()
}
