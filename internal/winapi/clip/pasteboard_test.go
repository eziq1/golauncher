package clip

import "testing"

func TestExcludedTypes(t *testing.T) {
	for _, tc := range []struct {
		types []string
		want  bool
	}{
		{nil, false},
		{[]string{"public.utf8-plain-text"}, false},
		{[]string{"public.utf8-plain-text", "org.nspasteboard.ConcealedType"}, true},
		{[]string{"org.nspasteboard.TransientType"}, true},
		{[]string{"public.png", "org.nspasteboard.AutoGeneratedType"}, true},
		{[]string{"com.agilebits.onepassword"}, true},
	} {
		if got := excludedTypes(tc.types); got != tc.want {
			t.Errorf("excludedTypes(%q) = %v, want %v", tc.types, got, tc.want)
		}
	}
}

