package clip

import "testing"

func TestExcludedTypes(t *testing.T) {
	for _, tc := range []struct {
		types []string
		want  bool
	}{
		{nil, false},
		{[]string{"public.utf8-plain-text"}, false},
		{[]string{"public.utf8-plain-text", "org.nspasteboard.ConcealedType"}, true},
		{[]string{"org.nspasteboard.TransientType"}, true},
		{[]string{"public.png", "org.nspasteboard.AutoGeneratedType"}, true},
		{[]string{"com.agilebits.onepassword"}, true},
	} {
		if got := excludedTypes(tc.types); got != tc.want {
			t.Errorf("excludedTypes(%q) = %v, want %v", tc.types, got, tc.want)
		}
	}
}

func TestFileURLPath(t *testing.T) {
	for _, tc := range []struct {
		in, want string
		ok       bool
	}{
		{"file:///Users/alice/Annual%20Report.pdf", "/Users/alice/Annual Report.pdf", true},
		{"file:///Users/alice/%E5%9B%BE%E7%89%87/", "/Users/alice/图片", true},
		{"file://localhost/tmp/x", "/tmp/x", true},
		{"file:///", "/", true},
		{"file://server/share/x", "", false},
		{"https://example.com/a", "", false},
		{"", "", false},
		{"not a url %zz", "", false},
	} {
		got, ok := fileURLPath(tc.in)
		if got != tc.want || ok != tc.ok {
			t.Errorf("fileURLPath(%q) = %q, %v; want %q, %v", tc.in, got, ok, tc.want, tc.ok)
		}
	}
}

