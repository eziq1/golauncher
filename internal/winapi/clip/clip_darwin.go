// The macOS clipboard is the general NSPasteboard, driven through the
// Objective-C runtime (internal/darwin/ns). It has no change notification:
// Watch polls its changeCount. It has no owner either: SourceApp is the
// frontmost application when the content is read, which is the app the
// user copied in for every change Watch reports promptly.

// Pasteboard types (UTIs).
const (
	typeText    = "public.utf8-plain-text"
	typePNG     = "public.png"
	typeTIFF    = "public.tiff"
	typeFileURL = "public.file-url"
	// The nspasteboard.org markers: content clipboard managers should not
	// record (passwords), content that is only on the clipboard briefly,
	// and content generated by a program rather than copied by the user.
	typeConcealed     = "org.nspasteboard.ConcealedType"
	typeTransient     = "org.nspasteboard.TransientType"
	typeAutoGenerated = "org.nspasteboard.AutoGeneratedType"
)

// pollInterval is how often Watch reads the pasteboard's changeCount.
const pollInterval = 300 * time.Millisecond

// pasteboard returns the general pasteboard (call inside ns.Pool).
func pasteboard() ns.ID {
	return ns.Send(ns.Class("NSPasteboard"), "generalPasteboard")
}

// changeCount returns the general pasteboard's change count.
func changeCount() int {
	var n int
	ns.Pool(func() { n = ns.SendInt(pasteboard(), "changeCount") })
	return n
}

// Read returns the current clipboard content: text and file URLs and, only
// when there is neither, an image as PNG (public.png, else converted from
// public.tiff). Content marked concealed, transient or auto-generated
// (nspasteboard.org; password managers write these) only has SourceApp and
// Exclude set. It is ReadWith(ReadOptions{Images: true}).
func Read() (plugin.ClipboardContent, error) {
	return ReadWith(ReadOptions{Images: true})
}

// ReadWith is Read with options: without Images no image data is
// requested, since that can make the source app render it.
func ReadWith(opts ReadOptions) (plugin.ClipboardContent, error) {
	if err := ns.Load(); err != nil {
		return plugin.ClipboardContent{}, fmt.Errorf("clip: %w", err)
	}
	var (
		c        plugin.ClipboardContent
		pngData  []byte
		tiffData []byte
	)
	ns.Pool(func() {
		c.SourceApp = frontmostName()
		pb := pasteboard()
		types := ns.Strings(ns.Send(pb, "types"))
		if c.Exclude = excludedTypes(types); c.Exclude {
			return
		}
		if contains(types, typeText) {
			c.Text = ns.GoString(ns.Send(pb, "stringForType:", ns.String(typeText)))
		}
		if contains(types, typeFileURL) {
			items := ns.Send(pb, "pasteboardItems")
			for i := range ns.SendInt(items, "count") {
				item := ns.Send(items, "objectAtIndex:", i)
				u := ns.GoString(ns.Send(item, "stringForType:", ns.String(typeFileURL)))
				if p, ok := fileURLPath(u); ok {
					c.Files = append(c.Files, p)
				}
			}
		}
		if !opts.Images || len(c.Files) > 0 || !blank(c.Text) {
			return
		}
		switch {
		case contains(types, typePNG):
			pngData = ns.Bytes(ns.Send(pb, "dataForType:", ns.String(typePNG)))
		case contains(types, typeTIFF):
			tiffData = ns.Bytes(ns.Send(pb, "dataForType:", ns.String(typeTIFF)))
		}
	})
	if c.Exclude {
		return plugin.ClipboardContent{SourceApp: c.SourceApp, Exclude: true}, nil
	}
	switch {
	case bytes.HasPrefix(pngData, pngSignature):
		c.Image = pngData
	case len(tiffData) > 0:
		c.Image = tiffToPNG(tiffData)
	}
	return c, nil
}

// tiffToPNG converts TIFF (or any format NSBitmapImageRep reads) to PNG,
// or returns nil.
func tiffToPNG(b []byte) []byte {
	var out []byte
	ns.Pool(func() {
		rep := ns.Send(ns.Class("NSBitmapImageRep"), "imageRepWithData:", ns.Data(b))
		if rep == 0 {
			return
		}
		const fileTypePNG = 4 // NSBitmapImageFileTypePNG
		props := ns.Send(ns.Class("NSDictionary"), "dictionary")
		out = ns.Bytes(ns.Send(rep, "representationUsingType:properties:", fileTypePNG, props))
	})
	if !bytes.HasPrefix(out, pngSignature) {
		return nil
	}
	return out
}

// pngToTIFF converts PNG to TIFF for apps that only read public.tiff, or
// returns nil.
func pngToTIFF(b []byte) []byte {
	var out []byte
	ns.Pool(func() {
		rep := ns.Send(ns.Class("NSBitmapImageRep"), "imageRepWithData:", ns.Data(b))
		out = ns.Bytes(ns.Send(rep, "TIFFRepresentation"))
	})
	return out
}

// lastWriteCount is the changeCount right after our last write; Watch
// ignores that change.
var lastWriteCount atomic.Int64

// pbData is one type of a clipboard write.
type pbData struct {
	typ  string
	data []byte
}

// write replaces the pasteboard content with one item holding text (when
// hasText) and the data types.
func write(text string, hasText bool, items ...pbData) error {
	if err := ns.Load(); err != nil {
		return fmt.Errorf("clip: %w", err)
	}
	var err error
	ns.Pool(func() {
		pb := pasteboard()
		ns.Send(pb, "clearContents")
		if hasText && !ns.SendBool(pb, "setString:forType:", ns.String(text), ns.String(typeText)) {
			err = errors.New("clip: the pasteboard refused the text")
			return
		}
		for _, it := range items {
			if !ns.SendBool(pb, "setData:forType:", ns.Data(it.data), ns.String(it.typ)) {
				err = fmt.Errorf("clip: the pasteboard refused %s", it.typ)
				return
			}
		}
		lastWriteCount.Store(int64(ns.SendInt(pb, "changeCount")))
	})
	return err
}

// WriteText replaces the clipboard content with text.
func WriteText(s string) error { return write(s, true) }

// WriteSecret is WriteText for secrets such as passwords: the content is
// also marked org.nspasteboard.ConcealedType, which clipboard managers
// (and this one) do not record.
func WriteSecret(s string) error {
	return write(s, true, pbData{typeConcealed, []byte{}})
}

// WriteImage replaces the clipboard content with a PNG image, offered as
// public.png and, for older apps, public.tiff.
func WriteImage(data []byte) error {
	if _, err := png.DecodeConfig(bytes.NewReader(data)); err != nil {
		return fmt.Errorf("clip: decode PNG: %w", err)
	}
	items := []pbData{{typePNG, data}}
	if tiff := pngToTIFF(data); len(tiff) > 0 {
		items = append(items, pbData{typeTIFF, tiff})
	}
	return write("", false, items...)
}

// WriteFiles replaces the clipboard content with a list of files, as file
// URLs that Finder pastes.
func WriteFiles(paths []string) error {
	if len(paths) == 0 {
		return errors.New("clip: no files")
	}
	if err := ns.Load(); err != nil {
		return fmt.Errorf("clip: %w", err)
	}
	var err error
	ns.Pool(func() {
		urls := make([]ns.ID, len(paths))
		for i, p := range paths {
			if abs, aerr := filepath.Abs(p); aerr == nil {
				p = abs
			}
			urls[i] = ns.Send(ns.Class("NSURL"), "fileURLWithPath:", ns.String(p))
		}
		pb := pasteboard()
		ns.Send(pb, "clearContents")
		if !ns.SendBool(pb, "writeObjects:", ns.Array(urls...)) {
			err = errors.New("clip: the pasteboard refused the files")
			return
		}
		lastWriteCount.Store(int64(ns.SendInt(pb, "changeCount")))
	})
	return err
}

// watchOwnWrites disables the filter that hides our own writes from Watch.
// Tests set it.
var watchOwnWrites atomic.Bool

// ownWrite reports whether the pasteboard content of change count n was
// written by this process.
func ownWrite(n int) bool {
	return !watchOwnWrites.Load() && int64(n) == lastWriteCount.Load()
}

// Watch calls fn after the clipboard changes. macOS has no notification, so
// the pasteboard's changeCount is polled every pollInterval; bursts of
// updates are coalesced and this process's own writes are ignored. stop
// ends the polling and waits for it; it is safe to call more than once.
func Watch(fn func()) (stop func(), err error) {
	if err := ns.Load(); err != nil {
		return nil, fmt.Errorf("clip: %w", err)
	}
	deb := &debouncer{delay: debounceDelay, fn: fn, hold: suppression.holding}
	quit := make(chan struct{})
	done := make(chan struct{})
	last := changeCount()
	go func() {
		defer close(done)
		t := time.NewTicker(pollInterval)
		defer t.Stop()
		for {
			select {
			case <-quit:
				return
			case <-t.C:
			}
			if n := changeCount(); n != last {
				last = n
				if !ownWrite(n) {
					deb.trigger()
				}
			}
		}
	}()
	var once sync.Once
	return func() {
		once.Do(func() {
			deb.stop()
			close(quit)
			<-done
		})
	}, nil
}

// frontmost returns NSWorkspace's frontmost application (inside ns.Pool).
func frontmost() ns.ID {
	return ns.Send(ns.Send(ns.Class("NSWorkspace"), "sharedWorkspace"), "frontmostApplication")
}

// pid returns the process identifier of an NSRunningApplication.
func pid(app ns.ID) int32 {
	if app == 0 {
		return 0
	}
	return objc.Send[int32](app, ns.Sel("processIdentifier"))
}

// frontmostName returns the executable name of the frontmost application
// (as Windows reports the clipboard owner's .exe name), or "" when that is
// this process (inside ns.Pool).
func frontmostName() string {
	app := frontmost()
	if app == 0 || int(pid(app)) == os.Getpid() {
		return ""
	}
	if exe := ns.GoString(ns.Send(ns.Send(app, "executableURL"), "lastPathComponent")); exe != "" {
		return exe
	}
	return ns.GoString(ns.Send(app, "localizedName"))
}

// ForegroundWindow returns the process identifier of the frontmost
// application, or 0. macOS pastes into apps, not windows: PasteTo takes it.
func ForegroundWindow() uintptr {
	if ns.Load() != nil {
		return 0
	}
	var p int32
	ns.Pool(func() { p = pid(frontmost()) })
	if p <= 0 {
		return 0
	}
	return uintptr(p)
}

// ErrNotTrusted is returned by PasteTo when golauncher is not allowed to
// send keystrokes (System Settings › Privacy & Security › Accessibility).
var ErrNotTrusted = errors.New("clip: golauncher needs Accessibility permission to paste (System Settings › Privacy & Security › Accessibility)")

// CoreGraphics and Accessibility functions, loaded on first use.
var quartz = sync.OnceValues(func() (*quartzFuncs, error) {
	lib, err := purego.Dlopen("/System/Library/Frameworks/ApplicationServices.framework/ApplicationServices",
		purego.RTLD_GLOBAL|purego.RTLD_NOW)
	if err != nil {
		return nil, fmt.Errorf("clip: %w", err)
	}
	q := &quartzFuncs{}
	purego.RegisterLibFunc(&q.axIsProcessTrusted, lib, "AXIsProcessTrusted")
	purego.RegisterLibFunc(&q.createKeyboardEvent, lib, "CGEventCreateKeyboardEvent")
	purego.RegisterLibFunc(&q.setFlags, lib, "CGEventSetFlags")
	purego.RegisterLibFunc(&q.post, lib, "CGEventPost")
	purego.RegisterLibFunc(&q.release, lib, "CFRelease")
	return q, nil
})

type quartzFuncs struct {
	axIsProcessTrusted  func() bool
	createKeyboardEvent func(source uintptr, key uint16, down bool) uintptr
	setFlags            func(event uintptr, flags uint64)
	post                func(tap uint32, event uintptr)
	release             func(ref uintptr)
}

// Trusted reports whether this process may send keystrokes to other apps
// (the Accessibility permission PasteTo needs).
func Trusted() bool {
	q, err := quartz()
	return err == nil && q.axIsProcessTrusted()
}

// activateTimeout bounds the wait for the target app to become frontmost.
const activateTimeout = 500 * time.Millisecond

// PasteTo brings the application with process identifier pid (from
// ForegroundWindow) to the front and sends ⌘V to it. It needs the
// Accessibility permission and returns ErrNotTrusted without it.
func PasteTo(target uintptr) error {
	if target == 0 {
		return errors.New("clip: invalid target application")
	}
	q, err := quartz()
	if err != nil {
		return err
	}
	if !q.axIsProcessTrusted() {
		return ErrNotTrusted
	}
	var ok bool
	ns.Pool(func() {
		app := ns.Send(ns.Class("NSRunningApplication"), "runningApplicationWithProcessIdentifier:", int32(target))
		if app == 0 {
			return
		}
		ok = true
		if pid(frontmost()) != int32(target) {
			const ignoringOtherApps = 1 << 1 // NSApplicationActivateIgnoringOtherApps
			ns.SendBool(app, "activateWithOptions:", ignoringOtherApps)
		}
	})
	if !ok {
		return errors.New("clip: the target application is no longer running")
	}
	if !waitFrontmost(int32(target), activateTimeout) {
		return ErrNotForeground
	}
	const (
		keyV        = 9       // kVK_ANSI_V
		flagCommand = 1 << 20 // kCGEventFlagMaskCommand
		hidTap      = 0       // kCGHIDEventTap
	)
	for _, down := range []bool{true, false} {
		ev := q.createKeyboardEvent(0, keyV, down)
		if ev == 0 {
			return errors.New("clip: CGEventCreateKeyboardEvent failed")
		}
		// Only ⌘: modifiers still held from the hotkey (⌥, ⇧) must not
		// turn the paste into another shortcut.
		q.setFlags(ev, flagCommand)
		q.post(hidTap, ev)
		q.release(ev)
	}
	return nil
}

// waitFrontmost waits until the app pid is frontmost or timeout passes.
func waitFrontmost(p int32, timeout time.Duration) bool {
	deadline := time.Now().Add(timeout)
	for {
		var cur int32
		ns.Pool(func() { cur = pid(frontmost()) })
		if cur == p {
			return true
		}
		if time.Now().After(deadline) {
			return false
		}
		time.Sleep(10 * time.Millisecond)
	}
}

